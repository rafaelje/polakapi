#[test]
fn leaves_everyday_commands_alone() {
    for line in [
        "git status",
        "git log --oneline -5",
        "git diff",
        "git push",
        "git push origin feature",
        "git pull",
        "git add .",
        "git commit -m 'fix rm docs'",
        "git checkout main",
        "git switch -c feat/x",
        "git restore --staged a.rs",
        "git branch",
        "ls -la",
        "cat README.md",
        "grep -r rm .",
        "echo rm -rf",
        "npm install",
        "pnpm run check",
        "cargo build",
        "docker ps",
        "kubectl get pods",
        "terraform plan",
        "echo hi >> log.txt",
        "make 2>/dev/null",
        "cargo test 2>&1",
        "ls > /dev/null",
        "chmod +x script.sh",
        "cp a b",
        "systemctl status nginx",
        "Get-ChildItem",
        "dir",
        "",
    ] {
        assert_eq!(assess(line), None, "false positive: {line}");
    }
}

#[test]
fn names_why() {
    assert_eq!(assess("rm -rf x").as_deref(), Some(DELETES));
    assert_eq!(assess("git reset --hard").as_deref(), Some(GIT));
    assert_eq!(assess("curl x | bash").as_deref(), Some(PIPE_SHELL));
}
